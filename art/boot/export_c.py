# Writes firmware/menu/src/bootanim.h: the launch animation (anim.py) for the menu.
# Usage: python3 export_c.py    (then rebuild the firmware)
# Sprites are column-major, 8 rows per byte (LSB = top), like the OLED and the menu's fb.
# The frame table is launch_params() frame by frame, so the menu plays exactly the GIF.
import os
from PIL import Image, ImageChops
import anim
from anim import L, LAUNCH_FRAMES, launch_params, launch, FINAL

OUT = os.path.join(anim.HERE, "..", "..", "firmware", "menu", "src", "bootanim.h")

def cols(im):
    pages = (im.height + 7) // 8
    out = []
    for x in range(im.width):
        for p in range(pages):
            b = 0
            for r in range(8):
                y = p * 8 + r
                if y < im.height and im.getpixel((x, y)): b |= 1 << r
            out.append(b)
    return out, pages

def carr(name, data):
    s = f"static const uint8_t {name}[{len(data)}] = {{\n"
    for i in range(0, len(data), 16):
        s += "  " + ",".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n"
    return s + "};\n"

# the caption as one sprite (characters at their final spacing)
c0x, cy = L["chars"][0][1]
cw = L["chars"][-1][1][0] + 5 - c0x
cap = Image.new("1", (cw, 7))
for im, (x, y) in L["chars"]: cap.paste(im, (x - c0x, 0), im)

sprites = [("BA_ISO", *L["iso"])] + [(f"BA_G{k}", im, p) for k, (im, p) in enumerate(L["glyphs"])] \
        + [("BA_CAP", cap, (c0x, cy))]
h = ["// Generated by art/boot/export_c.py from art/boot (anim.py, launch): do not edit.",
     "// Boot animation: sprites (column-major, LSB = top row) and the per-frame table.",
     "#pragma once", "#include <stdint.h>", ""]
total = 0
for name, im, (x, y) in sprites:
    d, pages = cols(im); total += len(d)
    h.append(f"#define {name}_X {x}\n#define {name}_Y {y}\n#define {name}_W {im.width}\n#define {name}_P {pages}")
    h.append(carr(name, d))
h.append(f"#define BA_FRAMES {LAUNCH_FRAMES}\n#define BA_CHAR_W {5 + 2}   // caption: 5 columns + 2 spacing\n")
h.append("// per frame: arrow dx, dy; P H dx; 2 6 dx; banana dy; caption chars shown; cursor x (0: none)")
rows = []
for f in range(LAUNCH_FRAMES):
    P = launch_params(f)
    v = [*P["arrow"], P["left"], P["right"], P["iso"], P["chars"], P["cursor"] or 0]
    assert all(-128 <= x < 128 for x in v[:5]) and 0 < (P["cursor"] or 1) < 256
    rows.append("  {" + ",".join(str(x) for x in v) + "},")
h.append(f"static const int8_t BA_TABLE[BA_FRAMES][7] = {{\n" + "\n".join(rows) + "\n};\n")
# the cursor x is unsigned in use; values above 127 are not used (asserted below)
assert all((launch_params(f)["cursor"] or 0) < 128 for f in range(LAUNCH_FRAMES))
assert ImageChops.difference(launch(LAUNCH_FRAMES - 1).convert("L"), FINAL.convert("L")).getbbox() is None
open(OUT, "w").write("\n".join(h))
print(f"{OUT}: {total} bytes of sprites, {LAUNCH_FRAMES * 7} bytes of table")
