"""TileData.h (256 tiles of 8 bytes) -> TileSet.h: the distinct tiles once (TileImages)
and the image number of each tile (TileIndex).

    python tools/tiles.py upstream/Source/MicroCity/TileData.h build/TileSet.h
"""
import re, sys

src, out = sys.argv[1:3]
data = [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', open(src).read())]
assert len(data) == 256 * 8, len(data)
images, index = [], []
for t in range(256):
    img = tuple(data[t * 8:t * 8 + 8])
    if img not in images: images.append(img)
    index.append(images.index(img))
with open(out, 'w') as f:
    f.write('// generated by tools/tiles.py from TileData.h\n')
    f.write('const uint8_t TileImages[] PROGMEM =\n{\n')
    for img in images: f.write('\t' + ', '.join('0x%02x' % b for b in img) + ',\n')
    f.write('};\nconst uint8_t TileIndex[256] PROGMEM =\n{\n')
    for i in range(0, 256, 16): f.write('\t' + ', '.join('%d' % n for n in index[i:i + 16]) + ',\n')
    f.write('};\n')
print(f'tiles: {len(images)} distinct of 256, {len(images) * 8 + 256} bytes instead of 2048')
