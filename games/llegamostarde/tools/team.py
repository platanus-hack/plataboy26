# The Platanus edition's characters: the Platanus team (and two friends from Buk), drawn
# by hand after their photos (platan.us/equipo, LinkedIn) in the original game's style:
# a 30 x 30 front sprite in the game's palette (csef.P), turned into the 3-tone portrait
# by gen_data.portrait() like the original characters. They all climb with one shared
# silhouette (the original Engineer's frames): the climbing sprite is a 15 x 15 back view,
# where they would hardly differ.
#
# The people: Paula Enei, Joaquín Stephens, Rafael Fernández, Sofía Clement, Ignacio
# Bernardo (Platanus), Lucía Uriarte, Felipe Sateler (Buk); the game shows their nicknames.
#
# Each character: its head (rows 0-9) and any overlay of the body (hair over the
# shoulders, prints), 20 columns wide (the sprite's columns 5-24), on a body template
# (shirt, sleeves, trousers, shoes). In the art: '.' keeps the template; the letters are
# the colors below; '|' and '!' are long hair (light / dark), drawn as strands.

# letter -> csef character (palette entry): lit (light), checkered (middle), outlined (dark)
COLORS = {
    'K': 'A',   # black                       dark
    'H': 'L',   # dark brown hair             dark
    'h': 'J',   # brown hair                  middle
    'S': ',',   # skin                        light
    's': '{',   # skin shadow, stubble        middle
    'W': 'G',   # white                       light
    'g': 'D',   # grey                        middle
    'n': 'B',   # navy, near black            dark
    'j': ':',   # denim                       middle
    'r': '[',   # red                         middle
    'p': '#',   # pink                        light
    'y': 'I',   # mustard                     light
    'o': '=',   # coral                       light
    'b': ':',   # blue                        middle
    'v': 'X',   # green                       middle
    '_': '.',   # transparent (erases the template)
}

def body(shirt, sleeves='long', pants='j', shoes='K', seam=None):
    """rows 10-29 of the template, 20 columns; seam: the arms' inner line"""
    c, e = shirt, seam or shirt
    rows = []
    rows.append('.....' + c * 4 + 'SS' + c * 4 + '.....')                       # 10 shoulders
    rows.append('....' + c * 12 + '....')                                      # 11
    for y in range(12, 18):
        arm = 'S' if sleeves == 'none' or (sleeves == 'short' and y >= 14) else c
        rows.append('....' + arm * 2 + e + c * 6 + e + arm * 2 + '....')       # 12-17
    rows.append('....SS' + e + c * 6 + e + 'SS....')                           # 18 hands
    rows.append('....SS' + pants * 8 + 'SS....')                               # 19
    rows += ['......' + pants * 8 + '......'] * 2                              # 20-21
    rows += ['......' + pants * 3 + '..' + pants * 3 + '......'] * 6           # 22-27
    rows += ['......' + shoes * 3 + '..' + shoes * 3 + '......'] * 2           # 28-29
    return rows

def pattern(cols, x, y):
    return cols[(x * 7 + y * 3 + (x * y) % 3) % len(cols)]

