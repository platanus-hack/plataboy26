def rows(ch):
    """the character's 30 x 30 front sprite, as csef rows"""
    grid = [['.'] * 20 for _ in range(30)]
    for y, r in enumerate(ch['body']):
        for x, c in enumerate(r): grid[10 + y][x] = c
    for y, r in enumerate(ch['art'].strip('\n').split('\n')):
        assert len(r) == 20, (ch['name'], y, r)
        for x, c in enumerate(r):
            if c != '.': grid[y][x] = c
    out = []
    for y, r in enumerate(grid):
        line = []
        for x, c in enumerate(r):
            if c == '*': c = pattern(ch['print'], x, y)
            elif c == '|': c = 'y' if x % 2 == 0 else 'K'          # long hair: strands
            elif c == '!': c = 'y' if x % 3 == 1 else 'K'          # long dark hair
            line.append(COLORS.get(c, c if c == '.' else '?'))
        assert '?' not in line, (ch['name'], y, ''.join(r))
        out.append(['.'] * 5 + line + ['.'] * 5)
    return out
