#!/usr/bin/env python3
# Builds src/sprites.h from tools/sprites.txt (1-bit art: '#' lit, 'o' dark but opaque,
# '.' transparent), as one bitstream (see main).
import sys

def load(path):
    out, name, rows = [], None, []
    for line in open(path).read().split('\n') + ['']:
        line = line.rstrip()
        if line.startswith(';'): continue
        if not line:
            if name: out.append((name, rows))
            name, rows = None, []
        elif name is None: name = line
        else: rows.append(line)
    return out

def main(src, dst):
    # Each sprite is a bitstream: column after column, h bits per column (bit 0 = top
    # row), first the lit plane, then (for sprites with dark pixels) the dark plane.
    sp = load(src)
    bits, table, enums, seen = [], [], [], set()
    for name, rows in sp:
        w, h = len(rows[0]), len(rows)
        assert all(len(r) == w for r in rows), name
        assert h <= 24 and w <= 31, name
        dark = any('o' in r for r in rows)
        bits += [0] * (-len(bits) % 8)       # each sprite starts on a byte
        ofs = len(bits) // 8
        for plane in ('#', 'o') if dark else ('#',):
            for x in range(w):
                bits += [1 if rows[y][x] == plane else 0 for y in range(h)]
        table.append((ofs, w, h, dark))
        base = name.split()[0]
        if base not in seen:
            seen.add(base); enums.append('SPR_%s = %d' % (base, len(table) - 1))
    bits += [0] * (32 + (-len(bits)) % 8)
    data = [sum(bits[i + k] << k for k in range(8)) for i in range(0, len(bits), 8)]
    assert len(data) < 2048
    with open(dst, 'w') as f:
        f.write('// generated by tools/sprites.py from tools/sprites.txt - do not edit\n#pragma once\n')
        f.write('enum { %s };\n' % ', '.join(enums))
        f.write('// byte offset (bits 0..10), width (11..15), height (16..20), dark plane (21)\n')
        f.write('static const uint8_t SPR[%d][3] = {\n' % len(table))
        for ofs, w, h, dark in table:
            v = ofs | w << 11 | h << 16 | dark << 21
            f.write('  {%d, %d, %d},\n' % (v & 255, v >> 8 & 255, v >> 16))
        f.write('};\nstatic const uint8_t SPR_DATA[%d] = {\n' % len(data))
        for i in range(0, len(data), 24):
            f.write('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
        f.write('};\n')
    print('sprites: %d, %d bytes' % (len(table), len(data) + 4 * len(table)))

main(sys.argv[1], sys.argv[2])
